let lang = 'en';

export function getLang() { return lang; }

export function setLang(l) {
  lang = l === 'ja' ? 'ja' : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function detectLang(preferred, navLang) {
  if (preferred === 'ja' || preferred === 'en') return preferred;
  return 'en'; // 既定は英語（端末の言語には従わない）。navLang は互換のために受け取るだけ。
}

/** 文言を取り出す。{name} を params で置き換える。キーがなければキーをそのまま返す。 */
export function t(key, params) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) ?? (STRINGS.en && STRINGS.en[key]) ?? (STRINGS.ja && STRINGS.ja[key]) ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}

/** data-i18n（本文）と data-i18n-title / data-i18n-placeholder / data-i18n-aria（属性）を反映する。 */
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
